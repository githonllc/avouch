// Runtime consistency: the evaluator, the runtime and the scenario must state one result for one invocation.
import { decide, externalResult, type Actor, type Bindings, type Snapshot, type Value } from "./evaluate.js";
import { fitsType, INVOCATION_RESULTS, isObj, own, type Stage1Ontology, type Type } from "./expr.js";

/** A result as the runtime or a scenario states it. `reason` only for INVALID_BINDING. No `param`: runtimes do not report it. */
export type Reported = { result: string; reason?: "missing" | "unknown_param" | "type" | "not_found" };

export interface RuntimeCase {
  id: string; // invocation id, generated by the harness
  action: string;
  snapshot: Snapshot | null; // typed snapshot taken before the invocation
  inputs: { bindings: Bindings; actor: Actor; scope: string | null; now: number };
  reported: Reported | null; // what the runtime reported; null = not reported
  expected: Reported | null; // the scenario expectation; null = none
}

export type CannotReconcile = "envelope" | "runtime_missing" | "expectation_missing" | "snapshot_missing" | "evaluator_error" | "runtime_unmapped" | "indeterminate" | "expectation_unmapped";

// `row` (the decision row that decide chose) is present only when the evaluator result is a domain result.
export type ReconcileRow =
  | { id: string; action: string; status: "match"; result: Reported; row?: number | "otherwise" }
  | { id: string; action: string; status: "mismatch"; evaluator: Reported; reported: Reported; expected: Reported; row?: number | "otherwise" }
  | { id: string; action: string; status: "cannot_reconcile"; reason: CannotReconcile; detail?: string };

/** Decodes one stored value of a property with a declared type; undefined = cannot decode. Never called with null. */
export type Decode = (raw: unknown, type: Type) => Value | undefined;
export type TypeDefect = { object: string; prop: string; row: string; value: unknown };
/** For each pure link id: the columns of its table that hold the `from` and `to` ids. */
export type LinkColumns = Readonly<Record<string, { readonly from: string; readonly to: string }>>;

// Only a plain object holds keys: a Buffer, Date, Map or typed array is a defect.
const isPlain = (x: unknown): x is Record<string, unknown> => isObj(x) && [Object.prototype, null].includes(Object.getPrototypeOf(x));

// Stored rows (physical values) -> a typed snapshot. Each property with a declared type is decoded and then checked with
// fitsType; a value that cannot be decoded or does not fit is a defect and keeps its raw value. Null is never decoded.
// An absent column is not projected (decide throws when it reads it: an incomplete snapshot). A pure link is projected only with a linkColumns entry; without one it fails closed.
// A property with `from` is not a column: it is the top-level key of the JSON object (a string or a plain object) in its field, or null; never decoded.
export function projectSnapshot(
  ont: Stage1Ontology,
  stores: Readonly<Record<string, readonly Readonly<Record<string, unknown>>[]>>,
  decode: Decode,
  linkColumns?: LinkColumns,
): { snapshot: Snapshot; defects: TypeDefect[] } {
  const datasources = new Set(Object.values(ont.objectTypes).map((o) => o.datasource));
  const links: NonNullable<Snapshot["links"]> = {};
  for (const l of ont.linkTypes) {
    if (l.table === undefined || datasources.has(l.table)) continue;
    const cols = own(linkColumns, l.id);
    if (cols === undefined) throw new Error(`pure link ${l.id} is not projected`);
    if (!Object.hasOwn(stores, l.table)) throw new Error(`snapshot lacks store ${l.table}`);
    links[l.id] = stores[l.table].map((stored) => {
      const { from: _from, to: _to, ...row }: Record<string, unknown> = stored;
      if (Object.hasOwn(stored, cols.from) && stored[cols.from] !== undefined) row.from = stored[cols.from];
      if (Object.hasOwn(stored, cols.to) && stored[cols.to] !== undefined) row.to = stored[cols.to];
      return row as Record<string, Value>;
    });
  }
  const objects: Snapshot["objects"] = {};
  const defects: TypeDefect[] = [];
  for (const [object, o] of Object.entries(ont.objectTypes)) {
    if (!Object.hasOwn(stores, o.datasource)) throw new Error(`snapshot lacks store ${o.datasource}`);
    objects[object] = stores[o.datasource].map((stored) => {
      const row: Record<string, unknown> = { ...stored };
      for (const [prop, p] of Object.entries(o.properties)) {
        const raw = row[prop];
        if (p.from !== undefined || p.type === undefined || raw === undefined || raw === null) continue;
        const v = decode(raw, p.type);
        if (v === undefined || !fitsType(v, p.type)) defects.push({ object, prop, row: String(row.id), value: raw });
        else row[prop] = v;
      }
      for (const [prop, p] of Object.entries(o.properties)) {
        if (p.from === undefined) continue;
        const raw = Object.hasOwn(row, p.from.field) ? row[p.from.field] : undefined;
        delete row[prop]; // a stored column with the name of a projected property is never used
        if (raw === undefined) continue;
        if (raw === null) {
          row[prop] = null;
          continue;
        }
        let json: unknown = raw;
        if (typeof raw === "string")
          try {
            json = JSON.parse(raw);
          } catch {
            json = undefined;
          }
        // an own key whose value is undefined is an absent key
        const v = isPlain(json) ? ((Object.hasOwn(json, p.from.key) ? json[p.from.key] : undefined) ?? null) : undefined;
        if (v === undefined) defects.push({ object, prop, row: String(row.id), value: raw });
        else if (v !== null && (p.type === undefined || !fitsType(v, p.type))) defects.push({ object, prop, row: String(row.id), value: v });
        else row[prop] = v;
      }
      return row as Record<string, Value>;
    });
  }
  return { snapshot: Object.keys(links).length > 0 ? { objects, links } : { objects }, defects };
}

// Strict on reason: both absent is equal; INVALID_BINDING with different reasons is not.
const same = (a: Reported, b: Reported): boolean => a.result === b.result && a.reason === b.reason;
const ENVELOPE = ["REPLAYED", "IDEMPOTENCY_CONFLICT"];
const INVOCATION: readonly string[] = INVOCATION_RESULTS;

// The domain results of an action: each distinct result of its decision rows, in row order, then of otherwise.
// An action without a decision table gives none. Names only; the class is ont.dispositions[name].class. For an ontology
// that passes the check, every name is a key of dispositions and none is an invocation result (R1).
export function domainResults(ont: Stage1Ontology, actionId: string): readonly string[] {
  const action = own(ont.actionTypes, actionId);
  if (action === undefined) throw new Error(`unknown action ${actionId}`);
  const names: string[] = [];
  for (const r of action.decision?.rows ?? []) if (!names.includes(r.result)) names.push(r.result);
  const o = action.decision?.otherwise;
  if (o !== undefined && !names.includes(o.result)) names.push(o.result);
  return names;
}

// One row per case, in input order. The evaluator result is computed only to compare: a missing runtime result or
// expectation is reported as such, never filled in from the decision table. Envelope results are not decisions (the
// evaluator does not implement the envelope; a replay does not recompute domain conditions), so decide is not called.
// A reported result that the action cannot give (runtime_unmapped) means the runtime did not report its domain result.
// An expected result that the action cannot give (expectation_unmapped) is a defect of the scenario.
export function reconcile(ont: Stage1Ontology, cases: readonly RuntimeCase[]): ReconcileRow[] {
  return cases.map((c): ReconcileRow => {
    const head = { id: c.id, action: c.action };
    const cannot = (reason: CannotReconcile, detail?: string): ReconcileRow => ({ ...head, status: "cannot_reconcile", reason, ...(detail !== undefined ? { detail } : {}) });
    const { reported, expected, snapshot } = c;
    if (reported === null) return cannot("runtime_missing");
    if (ENVELOPE.includes(reported.result)) return cannot("envelope");
    // A result this action can give: not SCOPE_DENIED (internal: SPEC section 9, Existence is not revealed), and an
    // invocation result or one of its domain results. The check reads only the ontology, so a runtime defect is found
    // also without an expectation, without a snapshot and when decide throws. An action that the ontology does not
    // have is not checked here: decide reports it (evaluator_error). A decision table that cannot be read skips the
    // check too: decide then throws and reports it.
    let results: readonly string[] | undefined;
    try {
      results = own(ont.actionTypes, c.action) !== undefined ? domainResults(ont, c.action) : undefined;
    } catch {
      results = undefined;
    }
    const mapped = (r: string): boolean => r !== "SCOPE_DENIED" && (INVOCATION.includes(r) || (results ?? []).includes(r));
    if (results !== undefined && !mapped(reported.result)) return cannot("runtime_unmapped", reported.result);
    if (expected === null) return cannot("expectation_missing");
    if (snapshot === null) return cannot("snapshot_missing");
    const { bindings, actor, scope, now } = c.inputs;
    let d: ReturnType<typeof decide>;
    try {
      d = decide(ont, c.action, snapshot, scope, bindings, actor, now);
    } catch (e) {
      return cannot("evaluator_error", e instanceof Error ? e.message : String(e));
    }
    // Defects of the input (runtime, then scenario) come before INDETERMINATE.
    if (!mapped(expected.result)) return cannot("expectation_unmapped", expected.result);
    if (d.layer === "indeterminate") return cannot("indeterminate", d.reason);
    const { result, reason } = externalResult(d);
    const evaluator: Reported = reason !== undefined ? { result, reason } : { result };
    const row = d.layer === "domain" ? { row: d.row } : {};
    return same(evaluator, reported) && same(evaluator, expected) ? { ...head, status: "match", result: evaluator, ...row } : { ...head, status: "mismatch", evaluator, reported, expected, ...row };
  });
}
